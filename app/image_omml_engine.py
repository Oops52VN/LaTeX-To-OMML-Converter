def recognize_formula_image_to_omml(
    image_input: Union[bytes, str, np.ndarray, Image.Image],
    padding: int = 14,
    xslt_transform=None
) -> Dict[str, Any]:
    """
    Main entry point for Image -> OMML conversion:
    1. Preprocesses image (Sauvola binarization, auto-crop, auto-inversion, padding).
    2. Runs Math OCR (PP-FormulaNet / Structural-2D).
    3. Normalizes LaTeX expression.
    4. Compiles normalized LaTeX directly into native Microsoft Word OMML and MathML.
    """
    t_start = time.perf_counter()
    try:
        # 1. Preprocessing
        prep_res = preprocess_for_math_ocr(image_input, padding=padding)
        ocr_input = prep_res["ocr_input_image"]

        # 2. OCR Recognition
        ocr_engine = MathImageOCREngine.get_instance()
        ocr_res = ocr_engine.recognize(ocr_input)

        if not ocr_res.get("success", False):
            return {
                "success": False,
                "error": ocr_res.get("error", "Math OCR recognition failed"),
                "enhanced_png_b64": prep_res.get("enhanced_png_b64", ""),
                "width": prep_res.get("width", 0),
                "height": prep_res.get("height", 0),
            }

        detected_latex = ocr_res["latex"]

        # 3. Direct AST -> OMML & MathML Compilation
        t_compile_0 = time.perf_counter()
        compile_res = latex_omml_engine.compile_raw_latex_for_studio(detected_latex)

        # Fallback to XSLT transform if custom direct AST compiler hit an unsupported syntax
        if not compile_res.get("success", False) and xslt_transform is not None:
            try:
                from app import convert_latex_snippet_to_omml
                xslt_res = convert_latex_snippet_to_omml(detected_latex, xslt_transform)
                if xslt_res.get("success", False):
                    compile_res = {
                        "success": True,
                        "latex": detected_latex,
                        "omml": xslt_res["omml"],
                        "mathml": xslt_res["mathml"],
                        "is_block": False,
                    }
            except Exception:
                pass

        t_compile = round((time.perf_counter() - t_compile_0) * 1000.0, 2)
        t_total = round((time.perf_counter() - t_start) * 1000.0, 2)

        return {
            "success": compile_res.get("success", False),
            "latex": detected_latex,
            "omml": compile_res.get("omml", ""),
            "mathml": compile_res.get("mathml", ""),
            "is_block": compile_res.get("is_block", False),
            "enhanced_png_b64": prep_res.get("enhanced_png_b64", ""),
            "width": prep_res.get("width", 0),
            "height": prep_res.get("height", 0),
            "crop_box": prep_res.get("crop_box", (0, 0, 0, 0)),
            "engine": ocr_res.get("engine", "PP-FormulaNet"),
            "time_preprocess_ms": prep_res.get("time_ms", 0.0),
            "time_ocr_ms": ocr_res.get("time_ms", 0.0),
            "time_compile_ms": t_compile,
            "time_total_ms": t_total,
            "error": compile_res.get("error", None)
        }
    finally:
        # Guarantee memory release and prevent RAM accumulation
        release_memory()
