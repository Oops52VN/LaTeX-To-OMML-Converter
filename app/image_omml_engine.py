class OCRLaTeXNormalizer:
    """Normalizes and repairs LaTeX expressions generated by Math OCR engines."""

    UNICODE_TO_LATEX: Dict[str, str] = {
        "±": r"\pm ", "∓": r"\mp ", "×": r"\times ", "·": r"\cdot ",
        "÷": r"\div ", "≤": r"\le ", "≥": r"\ge ", "≠": r"\ne ",
        "≈": r"\approx ", "≡": r"\equiv ", "∼": r"\sim ", "≃": r"\simeq ",
        "≪": r"\ll ", "≫": r"\gg ", "∝": r"\propto ", "⊥": r"\perp ",
        "∥": r"\parallel ", "⊂": r"\subset ", "⊃": r"\supset ",
        "⊆": r"\subseteq ", "⊇": r"\supseteq ", "∈": r"\in ", "∉": r"\notin ",
        "∋": r"\ni ", "∞": r"\infty ", "∂": r"\partial ", "∇": r"\nabla ",
        "∀": r"\forall ", "∃": r"\exists ", "∄": r"\nexists ", "∅": r"\emptyset ",
        "→": r"\to ", "←": r"\leftarrow ", "↔": r"\leftrightarrow ",
        "⇒": r"\implies ", "⇐": r"\Leftarrow ", "⇔": r"\iff ",
        "↑": r"\uparrow ", "↓": r"\downarrow ", "↦": r"\mapsto ",
        "∑": r"\sum ", "∏": r"\prod ", "∫": r"\int ", "∬": r"\iint ",
        "∭": r"\iiint ", "∮": r"\oint ", "√": r"\sqrt ",
        "α": r"\alpha ", "β": r"\beta ", "γ": r"\gamma ", "δ": r"\delta ",
        "ε": r"\varepsilon ", "ϵ": r"\epsilon ", "ζ": r"\zeta ", "η": r"\eta ",
        "θ": r"\theta ", "ϑ": r"\vartheta ", "ι": r"\iota ", "κ": r"\kappa ",
        "λ": r"\lambda ", "μ": r"\mu ", "ν": r"\nu ", "ξ": r"\xi ",
        "π": r"\pi ", "ρ": r"\rho ", "σ": r"\sigma ", "τ": r"\tau ",
        "υ": r"\upsilon ", "ϕ": r"\phi ", "φ": r"\varphi ", "χ": r"\chi ",
        "ψ": r"\psi ", "ω": r"\omega ", "Γ": r"\Gamma ", "Δ": r"\Delta ",
        "Θ": r"\Theta ", "Λ": r"\Lambda ", "Ξ": r"\Xi ", "Π": r"\Pi ",
        "Σ": r"\Sigma ", "Υ": r"\Upsilon ", "Φ": r"\Phi ", "Ψ": r"\Psi ",
        "Ω": r"\Omega ",
    }

    OPERATOR_FIXES: Dict[str, str] = {
        r"\operatorname{s q r t}": r"\sqrt",
        r"\operatorname{sqrt}": r"\sqrt",
        r"\operatorname{s i n}": r"\sin",
        r"\operatorname{sin}": r"\sin",
        r"\operatorname{c o s}": r"\cos",
        r"\operatorname{cos}": r"\cos",
        r"\operatorname{t a n}": r"\tan",
        r"\operatorname{tan}": r"\tan",
        r"\operatorname{c o t}": r"\cot",
        r"\operatorname{cot}": r"\cot",
        r"\operatorname{l i m}": r"\lim",
        r"\operatorname{lim}": r"\lim",
        r"\operatorname{l n}": r"\ln",
        r"\operatorname{ln}": r"\ln",
        r"\operatorname{l o g}": r"\log",
        r"\operatorname{log}": r"\log",
        r"\operatorname{e x p}": r"\exp",
        r"\operatorname{exp}": r"\exp",
        r"\operatorname{d e t}": r"\det",
        r"\operatorname{det}": r"\det",
        r"\operatorname{m a x}": r"\max",
        r"\operatorname{max}": r"\max",
        r"\operatorname{m i n}": r"\min",
        r"\operatorname{min}": r"\min",
    }

    @classmethod
    def normalize(cls, raw_latex: str) -> str:
        if not raw_latex:
            return ""

        text = raw_latex.strip()

        # 1. Strip surrounding display math markers if present
        if text.startswith("$$") and text.endswith("$$") and len(text) >= 4:
            text = text[2:-2].strip()
        elif text.startswith(r"\[") and text.endswith(r"\]") and len(text) >= 4:
            text = text[2:-2].strip()
        elif text.startswith("$") and text.endswith("$") and len(text) >= 2:
            text = text[1:-1].strip()
        elif text.startswith(r"\(") and text.endswith(r"\)") and len(text) >= 4:
            text = text[2:-2].strip()

        # 2. Fix OCR artifacts where ^ was parsed as ^{\Lambda} or similar
        text = re.sub(r"\^\{\\Lambda\}\s*(\d+|[a-zA-Z])", r"^\1", text)
        text = re.sub(r"\^\{\\Delta\}\s*(\d+|[a-zA-Z])", r"^\1", text)
        text = re.sub(r"_\{\\Lambda\}\s*(\d+|[a-zA-Z])", r"_\1", text)

        # 3. Fix fragmented operators: \operatorname{s q r t} -> \sqrt
        for bad_op, good_op in cls.OPERATOR_FIXES.items():
            text = text.replace(bad_op, good_op)

        # 4. Replace Unicode math symbols with standard LaTeX equivalents
        for u_char, lat_cmd in cls.UNICODE_TO_LATEX.items():
            if u_char in text:
                text = text.replace(u_char, lat_cmd)

        # 5. Fix common math spacing glitches: e.g. "m c ^ 2" -> "m c^2"
        text = re.sub(r"\s*\^\s*", "^", text)
        text = re.sub(r"\s*_\s*", "_", text)

        # 6. Fix function spacing: \sin x, \cos x
        text = re.sub(
            r"\\(sin|cos|tan|cot|sec|csc|log|ln|lim|arcsin|arccos|arctan)\s*([a-zA-Z0-9])",
            r"\\\1 \2",
            text
        )

        # 7. Balance grouping braces { ... }
        open_braces = text.count("{")
        close_braces = text.count("}")
        if open_braces > close_braces:
            text += "}" * (open_braces - close_braces)
        elif close_braces > open_braces:
            diff = close_braces - open_braces
            while diff > 0 and text.endswith("}"):
                text = text[:-1]
                diff -= 1

        # 8. Balance \left( ... \right)
        left_parens = len(re.findall(r"\\left\(", text))
        right_parens = len(re.findall(r"\\right\)", text))
        if left_parens > right_parens:
            text += r"\right)" * (left_parens - right_parens)
        elif right_parens > left_parens:
            text = r"\left(" * (right_parens - left_parens) + text

        left_brackets = len(re.findall(r"\\left\[", text))
        right_brackets = len(re.findall(r"\\right\]", text))
        if left_brackets > right_brackets:
            text += r"\right]" * (left_brackets - right_brackets)

        # 9. Clean excessive spaces
        text = re.sub(r"[ \t]+", " ", text).strip()

        return text


