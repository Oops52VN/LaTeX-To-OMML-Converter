def detect_dark_background(gray_img: np.ndarray) -> bool:
    """Detects if an image has a dark background (such as dark mode screenshots)."""
    h, w = gray_img.shape
    if h == 0 or w == 0:
        return False

    # Sample the 1-pixel border perimeter
    top = gray_img[0, :]
    bottom = gray_img[h - 1, :]
    left = gray_img[:, 0]
    right = gray_img[:, w - 1]

    border_pixels = np.concatenate([top, bottom, left, right])
    avg_border = float(np.mean(border_pixels))
    median_all = float(np.median(gray_img))

    # If border is dark or median is dark, it's dark background with light ink
    return avg_border < 128 or median_all < 110


def preprocess_for_math_ocr(
    image_input: Union[bytes, str, np.ndarray, Image.Image],
    padding: int = 14,
    min_height: int = 48
) -> Dict[str, Any]:
    """
    Comprehensive mathematical formula image preprocessing:
    - Auto dark-background detection & inversion
    - Noise reduction (3x3 median blur)
    - Sauvola adaptive binarization / Otsu
    - Auto-cropping of ink bounding box
    - Aspect-preserving Lanczos upscaling for small formulas
    - Base64 PNG generation for UI display
    """
    t0 = time.perf_counter()

    # Step 1: Decode input into BGR/Grayscale numpy array and raw bytes
    raw_bytes: bytes
    if isinstance(image_input, bytes):
        raw_bytes = image_input
        np_arr = np.frombuffer(raw_bytes, np.uint8)
        bgr_img = cv2.imdecode(np_arr, cv2.IMREAD_COLOR)
    elif isinstance(image_input, str):
        if image_input.startswith("data:image"):
            image_input = image_input.split(",", 1)[1]
        try:
            raw_bytes = base64.b64decode(image_input)
            np_arr = np.frombuffer(raw_bytes, np.uint8)
            bgr_img = cv2.imdecode(np_arr, cv2.IMREAD_COLOR)
        except Exception:
            # File path
            with open(image_input, "rb") as f:
                raw_bytes = f.read()
            bgr_img = cv2.imread(image_input, cv2.IMREAD_COLOR)
    elif isinstance(image_input, np.ndarray):
        bgr_img = image_input if len(image_input.shape) == 3 else cv2.cvtColor(image_input, cv2.COLOR_GRAY2BGR)
        _, buf = cv2.imencode(".png", bgr_img)
        raw_bytes = buf.tobytes()
    elif isinstance(image_input, Image.Image):
        buf = io.BytesIO()
        image_input.save(buf, format="PNG")
        raw_bytes = buf.getvalue()
        bgr_img = cv2.cvtColor(np.array(image_input), cv2.COLOR_RGB2BGR)
    else:
        raise ValueError(f"Unsupported image input type: {type(image_input)}")

    if bgr_img is None or bgr_img.size == 0:
        raise ValueError("Failed to decode image input.")

    gray = cv2.cvtColor(bgr_img, cv2.COLOR_BGR2GRAY)
    is_dark = detect_dark_background(gray)
    if is_dark:
        gray = 255 - gray
        bgr_img = 255 - bgr_img
        _, buf = cv2.imencode(".png", bgr_img)
        raw_bytes = buf.tobytes()

    # Step 2: High-speed Sauvola binarization + auto-crop
    enhanced_png_bytes: bytes
    crop_w: int
    crop_h: int
    crop_box: Tuple[int, int, int, int]

    if HAS_RUST_CORE:
        try:
            res = quast_core.preprocess_formula_image(
                raw_bytes,
                window_size=25,
                k=0.18,
                padding=padding,
                denoise=True
            )
            enhanced_png_bytes = bytes(res.png_bytes)
            crop_w = res.width
            crop_h = res.height
            crop_box = res.crop_box
        except Exception:
            enhanced_png_bytes, crop_w, crop_h, crop_box = _python_preprocess(gray, padding)
    else:
        enhanced_png_bytes, crop_w, crop_h, crop_box = _python_preprocess(gray, padding)

    # Step 3: Decode preprocessed image for OCR feeding
    enhanced_arr = np.frombuffer(enhanced_png_bytes, np.uint8)
    enhanced_cv = cv2.imdecode(enhanced_arr, cv2.IMREAD_COLOR)

    # Step 4: If height is too small (< 48px), upscale using Lanczos for OCR clarity
    ocr_input = enhanced_cv
    cur_h, cur_w = enhanced_cv.shape[:2]
    if cur_h < min_height and cur_h > 0:
        scale = min_height / float(cur_h)
        new_w = max(1, int(round(cur_w * scale)))
        ocr_input = cv2.resize(enhanced_cv, (new_w, min_height), interpolation=cv2.INTER_LANCZOS4)

    enhanced_b64 = base64.b64encode(enhanced_png_bytes).decode("ascii")
    t_elapsed = round((time.perf_counter() - t0) * 1000.0, 2)

    return {
        "success": True,
        "enhanced_png_bytes": enhanced_png_bytes,
        "enhanced_png_b64": enhanced_b64,
        "ocr_input_image": ocr_input,
        "width": crop_w,
        "height": crop_h,
        "crop_box": crop_box,
        "is_dark_inverted": is_dark,
        "time_ms": t_elapsed
    }


def _python_preprocess(
    gray: np.ndarray,
    padding: int
) -> Tuple[bytes, int, int, Tuple[int, int, int, int]]:
    """Pure Python + OpenCV fallback for image binarization and cropping."""
    # 1. Median filter 3x3
    denoised = cv2.medianBlur(gray, 3)

    # 2. Otsu thresholding
    _, thresh = cv2.threshold(denoised, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)

    # 3. Find ink contours (pixels < 128)
    points = cv2.findNonZero(255 - thresh)
    h, w = thresh.shape
    if points is not None:
        x, y, bw, bh = cv2.boundingRect(points)
        cropped = thresh[y:y + bh, x:x + bw]
        crop_box = (int(x), int(y), int(bw), int(bh))
    else:
        cropped = thresh
        crop_box = (0, 0, int(w), int(h))

    # 4. Add uniform white padding
    padded = cv2.copyMakeBorder(
        cropped,
        padding, padding, padding, padding,
        cv2.BORDER_CONSTANT,
        value=255
    )

    _, enc = cv2.imencode(".png", padded)
    out_h, out_w = padded.shape[:2]
    return enc.tobytes(), out_w, out_h, crop_box


