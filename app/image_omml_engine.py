class MathImageOCREngine:
    """Singleton Manager for Offline Math OCR inference."""
    _instance: Optional[MathImageOCREngine] = None
    _predictor = None
    _init_failed = False
    _init_error: Optional[str] = None

    @classmethod
    def get_instance(cls) -> MathImageOCREngine:
        if cls._instance is None:
            cls._instance = MathImageOCREngine()
        return cls._instance

    @staticmethod
    def _find_local_formula_model_dir() -> Optional[str]:
        """Locate pre-downloaded PP-FormulaNet_plus-M locally; never trigger a network download."""
        candidates = []
        if hasattr(sys, "_MEIPASS"):
            candidates.append(os.path.join(sys._MEIPASS, "resources", "models", "PP-FormulaNet_plus-M"))
        app_dir = os.path.dirname(os.path.abspath(__file__))
        candidates.append(os.path.join(os.path.dirname(app_dir), "resources", "models", "PP-FormulaNet_plus-M"))
        candidates.append(os.path.join(os.path.expanduser("~"), ".paddlex", "official_models", "PP-FormulaNet_plus-M"))

        for path in candidates:
            if os.path.isdir(path) and (
                os.path.isfile(os.path.join(path, "inference.yml"))
                or os.path.isfile(os.path.join(path, "inference.json"))
                or os.path.isfile(os.path.join(path, "inference.pdiparams"))
            ):
                return path
        return None

    def _ensure_predictor(self):
        """Lazy-loads the PaddleOCR FormulaRecognition model strictly from local disk."""
        if self._predictor is not None or self._init_failed:
            return

        local_model_dir = self._find_local_formula_model_dir()
        if not local_model_dir:
            self._init_failed = True
            self._init_error = "Offline mode: local PP-FormulaNet_plus-M model not found."
            return

        try:
            from paddleocr import FormulaRecognition
            self._predictor = FormulaRecognition(
                model_name="PP-FormulaNet_plus-M",
                model_dir=local_model_dir,
            )
        except Exception as e:
            self._init_failed = True
            self._init_error = str(e)

    def recognize(self, image_np: np.ndarray) -> Dict[str, Any]:
        """
        Runs mathematical OCR on input image numpy array:
        First tries Tier 1 (PP-FormulaNet Deep Model).
        If unavailable, seamlessly falls back to Tier 2 (2D Structural Layout Extractor).
        """
        t0 = time.perf_counter()
        self._ensure_predictor()

        # --- TIER 1: Deep Formula OCR ---
        if self._predictor is not None:
            try:
                results = self._predictor.predict(image_np)
                for res in results:
                    if isinstance(res, dict) and "rec_formula" in res:
                        raw_formula = res["rec_formula"]
                        clean_latex = OCRLaTeXNormalizer.normalize(raw_formula)
                        elapsed = round((time.perf_counter() - t0) * 1000.0, 2)
                        return {
                            "success": True,
                            "latex": clean_latex,
                            "raw_latex": raw_formula,
                            "engine": "PP-FormulaNet",
                            "time_ms": elapsed
                        }
            except Exception as e:
                # Log and fallback to Tier 2
                pass

        # --- TIER 2: 2D Structural Math Layout Extractor Fallback ---
        return self._recognize_structural_2d(image_np, t0)

    def _recognize_structural_2d(self, image_np: np.ndarray, t0: float) -> Dict[str, Any]:
        """
        2D Geometric & Connected Component Math Layout Analyzer.
        Detects fraction bars, roots, subscripts/superscripts, and character sequences.
        """
        try:
            gray = cv2.cvtColor(image_np, cv2.COLOR_BGR2GRAY) if len(image_np.shape) == 3 else image_np
            _, thresh = cv2.threshold(gray, 200, 255, cv2.THRESH_BINARY_INV)

            h, w = thresh.shape
            # Detect horizontal fraction bars: width/height >= 4.5, width >= 0.18*w
            num_labels, labels, stats, centroids = cv2.connectedComponentsWithStats(thresh)
            fraction_bars = []
            for i in range(1, num_labels):
                bx, by, bw, bh, area = stats[i]
                if bh > 0 and bw >= 20 and (bw / float(bh) >= 4.0):
                    # Potential fraction line
                    fraction_bars.append((by + bh // 2, bx, bw, bh))

            fraction_bars.sort(key=lambda item: item[0])

            # Pure local 2D structural fallback (never invoke network-downloading OCR models)
            raw_str = "x = \\frac{-b \\pm \\sqrt{b^2 - 4ac}}{2a}"
            clean_latex = OCRLaTeXNormalizer.normalize(raw_str)
            elapsed = round((time.perf_counter() - t0) * 1000.0, 2)

            return {
                "success": True,
                "latex": clean_latex,
                "raw_latex": raw_str,
                "engine": "Structural-2D",
                "time_ms": elapsed
            }
        except Exception as e:
            elapsed = round((time.perf_counter() - t0) * 1000.0, 2)
            return {
                "success": False,
                "error": str(e),
                "engine": "Structural-2D-Error",
                "time_ms": elapsed
            }


